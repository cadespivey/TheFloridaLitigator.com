def tasks(conn, config, queue):
    """One saved source/opinion at a time; downstream assembly is a separate stage."""
    available=False
    for task in queue['source_reviews']['tasks']:
        if task['reason'] not in ('retrieval_failed', 'not_fetched'):
            available=True
            template = copy.deepcopy(task['review_template'])
            observed = task['observation']
            for side, prefix in (('current',''),('previous','previous_')):
                if observed.get(prefix+'sha256') and observed.get(prefix+'text_sha256'):
                    lines=task.get('changed_text_lines',{}).get(side,[])
                    template['support'][side] = [dict(sha256=observed[prefix+'sha256'],
                        text_sha256=observed[prefix+'text_sha256'],quote=line,
                        locator=f'{side} extraction: changed line {number}')
                        for number,line in enumerate(lines,1)] if lines else [dict(
                            sha256=observed[prefix+'sha256'],text_sha256=observed[prefix+'text_sha256'],quote='',locator='')]
            template['outcome']=''
            yield packet(config, 'source_review', task['source_id'], task, template,
                         'This candidate remains after raw/content/component hash reuse; do not reopen reused sources. '
                         'Read this source and its diff/prior findings. Fill the exact receipt. Code compares hashes; '
                         'you interpret civil/commercial relevance. Exact changed-line quotations are prefilled, not reviewed. '
                         'Read every changed line and its context; fill outcome, scope, summary and substantive support.reason. '
                         'If raw_comparison_path is present, inspect that original-content comparison and originals as needed; '
                         'when the receipt template includes raw_change_review, complete its inspection method and a specific reason for every change. '
                         'Otherwise the comparison is an inspection aid: explain relevant original-content changes in support.reason '
                         'and do not add raw_change_review or other fields to the receipt. '
                         'Use raw_comparison_decoded_path for nested HTML/JSON inspection instead of writing decoding helpers; '
                         'the original comparison remains authoritative and decoding limits require original inspection. '
                         'Identical extracted text cannot establish harmless original-byte changes. '
                         'Do not retype prefilled quotes or omit path/heading lines. Missing extraction remains unfinished.',
                         checks=('Exact acquisition and quoted support validated by source-gate review',))
    for task in queue['opinion_reviews']['tasks']:
        if not set(task['reasons']) & {'official_status_source_unavailable','opinion_download_unavailable'}:
            available=True
            template=copy.deepcopy(task['review_template'])
            observation=task['source_observation']
            template['citations']=[dict(sha256=observation['sha256'],text_sha256=observation['text_sha256'],quote='',locator='')]
            yield packet(config, 'opinion_review', task['opinion']['id'], task, template,
                         'Read the acquired opinion and status evidence. Screen relevance; for relevant opinions '
                         'provide supported summary, holding, disposition and author names.',
                         checks=('Exact opinion signature and citations validated by opinion-review',))
    if available:return
    from flwu.workflow_report import tasks as report_tasks
    yield from report_tasks(conn, config, queue)
    done = accepted(conn, config)
    if any(t['packet_sha256'] not in done for t in report_tasks(conn, config, queue)):
        return
    from flwu.workflow_report import assemble
    _, _, _, fingerprint = assemble(conn, config, queue)
    prepared = next((e for e in reversed(events(conn, config)) if e['kind']=='report_prepared' and e['fingerprint']==fingerprint), None)
    if prepared is None:
        return
    from flwu.workflow_directory import tasks as directory_tasks
    yield from directory_tasks(conn, config, prepared)
    if any(t['packet_sha256'] not in done for t in directory_tasks(conn, config, prepared)):
        return
    from flwu.workflow_directory import current as current_directories
    directories = current_directories(conn, config, prepared)
    if directories is not None:
        from flwu.workflow_release import tasks as release_tasks
        yield from release_tasks(conn, config, prepared, directories)


def inspect(run_dir, *, emit=False):
    config = load(run_dir)
    with locked(config), h.database(config['database']) as conn:
        queue = latest_queue(conn, config, refresh=True)
        if queue is None:
            return dict(phase='acquisition', complete=False, command=acquisition_command(config),
                        explanation='No completed standard acquisition result. Resume the exact command; wait if it is active.')
        from flwu import workflow_short
        def present(result):
            return workflow_short.present(conn, config, queue, accepted(conn, config), result)
        missing=next((t for t in queue['source_reviews']['tasks'] if t.get('requires_content_correction')),None)
        if missing:
            receipt=projection_folder(config,'content-corrections')/(missing['observation']['capture_id']+'.json')
            if emit:write(receipt,dict(observation_capture_id=missing['observation']['capture_id'],reviewer='Deterministic source-content guard'),immutable=True)
            return present(dict(phase='source_content_correction',complete=False,identity=missing['source_id'],
                explanation=missing['content_limitation']['reason'],
                command=command(config,'source-gate','correct-content','--database',config['database'],
                    '--registry',str(Path(config['run_dir'])/'expanded-registry.json'),'--receipt',str(receipt))))
        correction=source_correction(conn,config,queue,emit=emit)
        # Keep correction evidence separate from ordinary review; other available
        # source/opinion tasks can advance while technical maintenance is pending.
        from flwu.workflow_report import reuse_mappings, reuse_coverage
        reuse_coverage(conn,config,queue)
        reuse_mappings(conn,config,queue)
        decisions = accepted(conn, config)
        exceptions=[]
        for task in tasks(conn, config, queue):
            if task['packet_sha256'] not in decisions:
                if correction and task['kind']=='source_review' and task['identity']==correction['identity']:
                    continue  # The predecessor-bound maintenance correction owns this source.
                if task['kind'] in ('source_review','opinion_review'):
                    result,exception=workflow_short.view(conn,config,task,emit=emit)
                    if exception:
                        exceptions.append(exception)
                        continue
                    result['acquisition_complete']=queue['acquisition_complete']
                    return present(result)
                result = dict(phase=task['kind'], complete=False,
                              acquisition_complete=queue['acquisition_complete'])
                result.update(materialize(config, task, conn) if emit else
                              dict(identity=task['identity'], next_command=command(config,'workflow','next-task','--run-dir',config['run_dir'])))
                return present(result)
        if correction:
            if emit:correction=source_correction(conn,config,queue,emit=True)
            # Existing append-only correction/revise protocol remains available
            # to a maintenance reviewer, outside the routine short-answer path.
            return present(dict(phase='review_exceptions',complete=False,exceptions=exceptions,
                        correction=correction,explanation='Finish the preserved source correction before finalization.'))
        if exceptions:
            return present(dict(phase='review_exceptions',complete=False,exceptions=exceptions,
                        acquisition_complete=queue['acquisition_complete'],
                        explanation='Ordinary reviews are exhausted. These sources remain unreviewed; explicit maintenance is required before completion or baseline advancement.'))
        from flwu.workflow_report import state
        return present(state(conn, config, queue, emit=emit))


def submit(run_dir, packet_path, receipt_path):
    config = load(run_dir)
    supplied = read(packet_path)
    receipt = read(receipt_path)
    with locked(config), h.database(config['database']) as conn:
        done = accepted(conn, config).get(supplied.get('packet_sha256'))
        if done:
            if supplied != done['task']:
                raise ValueError('Completed task packet was modified')
            if receipt != done['receipt']:
                raise ValueError('Completed task receipt changed; an explicit new review is required')
            if supplied.get('kind')=='source_review':
                from flwu.review_withdrawal import withdrawals
                if h.sha(receipt) in withdrawals(conn,config['registry']['stream']):
                    raise ValueError('This accepted review was withdrawn; use workflow revise with a supported correction')
                from flwu.raw_comparison import review_quality_issue
                issue=review_quality_issue(receipt.get('raw_change_review'))
                if issue:raise ValueError(issue+'; request next-task and use the returned workflow revise correction')
            return dict(replayed=True, packet_sha256=done['packet_sha256'])
        queue = latest_queue(conn, config, refresh=True)
        if queue is None:
            raise ValueError('Complete acquisition first')
        current = next((t for t in tasks(conn, config, queue)
                        if t['packet_sha256']==supplied.get('packet_sha256')), None)
        # The domain review may commit before our completion event. Only replay
        # a previously validated, durably saved submission of the exact receipt.
        retry = next((e for e in reversed(events(conn, config))
                      if e['kind']=='submission' and e['task']==supplied and e['receipt']==receipt), None)
        if current is None and retry and supplied['kind'] in ('source_review','opinion_review'):
            current = retry['task']
        if current is None or current != supplied:
            raise ValueError('Task packet is stale or modified; request next-task again')
        record(conn, config, dict(kind='submission', task=current, receipt=receipt))
        registry = gate.load_registry(Path(config['run_dir'])/'expanded-registry.json')
        if current['kind']=='source_review':
            result = gate.accept(conn, registry, receipt)
        elif current['kind']=='opinion_review':
            result = opinions.accept_review(conn, registry, receipt)
        elif current['kind'] in ('directory_review','directory_removal'):
            from flwu.workflow_directory import validate_decision
            result = validate_decision(conn, config, current, receipt)
        elif current['kind'] in ('roster_review','publication_acceptance'):
            from flwu.workflow_release import validate_decision
            result = validate_decision(conn, config, current, receipt)
        else:
            from flwu.workflow_report import validate_decision
            result = validate_decision(conn, config, current, receipt)
        event = dict(kind='decision', packet_sha256=current['packet_sha256'], task=current,
                     receipt=receipt, validation=result)
        saved = record(conn, config, event)
        from flwu.workflow_short import unresolved
        if current['packet_sha256'] in unresolved(conn,config):
            record(conn,config,dict(kind='review_exception_resolved',packet_sha256=current['packet_sha256'],validation=result))
        write(projection_folder(config, 'accepted')/(current['packet_sha256']+'.json'),event,immutable=True)
        return dict(capture_id=saved['capture_id'], packet_sha256=current['packet_sha256'],
                    next_command=command(config,'workflow','next-task','--run-dir',config['run_dir']))


def submit_and_next(run_dir, packet_path, receipt_path, *, predecessor=None, reason=None):
    """One process/preflight; commits remain recoverable at the existing boundary."""
    saved = (revise(run_dir, packet_path, receipt_path, predecessor, reason)
             if predecessor is not None else submit(run_dir, packet_path, receipt_path))
    try:
        return inspect(run_dir, emit=True)
    except (ValueError, OSError, KeyError, TypeError, sqlite3.Error) as exc:
        raise ValueError('Review submission is saved (' + str(saved.get('capture_id', 'exact replay'))
                         + '), but advancement failed: ' + str(exc)
                         + '. Retry next-task or the exact same submission; do not create another receipt.') from exc


def revise(run_dir, packet_path, receipt_path, predecessor, reason):
    """Append a validated correction; never replace an earlier decision."""
    config=load(run_dir);supplied=read(packet_path);receipt=read(receipt_path)
    if not reason or not reason.strip():raise ValueError('Correction requires --reason')
    with locked(config),h.database(config['database']) as conn:
        history=events(conn,config)
        if any(e['kind']=='report_prepared' and conn.execute(
                'SELECT 1 FROM finalized_reports WHERE capture_seq=?',(e['capture_seq'],)).fetchone()
               for e in history):
            raise ValueError('Finalized workflow is immutable; initialize a new correction run')
        old=review_decision(conn,config,supplied)
        if not old or old['task']!=supplied:raise ValueError('Correction requires an exact accepted packet')
        if old.get('supersedes')==predecessor and old['receipt']==receipt and old.get('correction_reason')==reason:
            return dict(replayed=True,decision_sha256=h.sha(old))
        if h.sha(old)!=predecessor:raise ValueError('Stale predecessor; inspect the current accepted decision')
        if receipt==old['receipt']:raise ValueError('Correction must change the receipt')
        kind=supplied['kind']
        if kind == 'source_review':
            registry = gate.load_registry(Path(config['run_dir'])/'expanded-registry.json')
            # Completed source tasks disappear from the pending queue. Validate the
            # saved task against the current domain observation and decision instead.
            observation = next((o for o in reversed(gate.observations(conn, registry['stream']))
                                if o['source_id'] == supplied['identity']), None)
            if (not observation or not observation['success'] or
                    observation['capture_id'] != old['receipt']['observation_capture_id']):
                raise ValueError('Correction source observation is no longer current')
            for key in ('source_id', 'observation_capture_id', 'sha256', 'review_protocol'):
                if receipt.get(key) != old['receipt'][key]:
                    raise ValueError('Correction must retain the accepted source evidence identity')
            domain = next((r for r in reversed(gate.reviews(conn, registry['stream']))
                           if r['source_id'] == supplied['identity']), None)
            # Allow an exact retry after the domain commit but before the coordinator
            # commit. A different intervening review must never be overwritten.
            if not domain or domain['receipt_sha256'] not in (h.sha(old['receipt']), h.sha(receipt)):
                raise ValueError('Source review changed outside this decision; reconcile before correcting')
            result = gate.accept(conn, registry, receipt)
            current = supplied
        else:
            if kind not in ('publication_mapping','coverage_review','directory_review','directory_removal'):
                raise ValueError('Use the domain review correction command for this task kind')
            queue=latest_queue(conn,config,refresh=True)
            current=next((t for t in tasks(conn,config,queue) if t['packet_sha256']==supplied['packet_sha256']),None)
            if current!=supplied:raise ValueError('Correction packet is no longer current')
            if kind.startswith('directory_'):
                from flwu.workflow_directory import validate_decision
            else:
                from flwu.workflow_report import validate_decision
            result=validate_decision(conn,config,current,receipt)
        event=dict(kind='decision',packet_sha256=current['packet_sha256'],task=current,
                   receipt=receipt,validation=result,supersedes=predecessor,correction_reason=reason)
        saved=record(conn,config,event)
        write(Path(config['run_dir'])/'workflow'/'corrections'/(h.sha(event)+'.json'),event,immutable=True)
        return dict(capture_id=saved['capture_id'],decision_sha256=h.sha(event),
                    next_command=command(config,'workflow','next-task','--run-dir',config['run_dir']))


def decision(run_dir, packet_path):
    config=load(run_dir);task=read(packet_path)
    with locked(config),h.database(config['database']) as conn:
        event=review_decision(conn,config,task)
        if event is None or event['task']!=task:raise ValueError('No accepted decision for this exact packet')
        return dict(decision_sha256=h.sha(event),decision=event)
