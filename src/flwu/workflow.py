def read(path):
    return json.loads(Path(path).read_text())


def write(path, value, *, immutable=False):
    """Atomic projection; interrupted writes cannot masquerade as completed JSON."""
    path = Path(path)
    raw = (json.dumps(value, indent=2, ensure_ascii=False, sort_keys=True) + '\n').encode()
    path.parent.mkdir(parents=True, exist_ok=True)
    if immutable and path.exists():
        if path.read_bytes() != raw:
            raise ValueError('Immutable workflow artifact differs: ' + str(path))
        return path
    fd, temporary = tempfile.mkstemp(prefix='.'+path.name, dir=path.parent)
    try:
        with os.fdopen(fd, 'wb') as handle:
            handle.write(raw)
            handle.flush()
            os.fsync(handle.fileno())
        if immutable:
            try:
                os.link(temporary, path)
            except FileExistsError:
                if path.read_bytes() != raw:
                    raise ValueError('Concurrent workflow artifact differs: ' + str(path)) from None
        else:
            os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)
    return path


def stream(config):
    return 'workflow:' + h.sha(config)


def events(conn, config):
    return [json.loads(r['payload'])['workflow'] for r in conn.execute(
        'SELECT payload FROM captures WHERE stream=? ORDER BY seq', (stream(config),))]


def record(conn, config, event):
    payload = dict(status='incomplete', contract={}, checks=[], findings=[], drafts=[], workflow=event)
    artifacts={h.sha(event):h.canonical(event).encode()}
    for path,digest in event.get('projection_hashes',{}).items():
        raw=Path(path).read_bytes()
        if h.sha(raw)!=digest:raise ValueError('Projection changed before persistence')
        artifacts[digest]=raw
    return h.record(conn, stream=stream(config), mode='manual_research',
                    scope={'workflow_contract':h.sha(config)}, run_id=h.sha(event),
                    payload=payload, artifacts=artifacts)


def projection_hashes(paths):
    return {str(p):h.sha(Path(p).read_bytes()) for p in paths}


def verify_projections(event):
    for path,digest in event.get('projection_hashes',{}).items():
        if not Path(path).is_file() or h.sha(Path(path).read_bytes())!=digest:
            raise ValueError('Generated projection missing or changed; run workflow repair --run-dir RUN')


def preserve_attempt(conn,config,folder):
    """Move a generated stage aside before explicit regeneration, never delete it."""
    folder=Path(folder)
    if not folder.resolve().is_relative_to(Path(config['run_dir']).resolve()):
        raise ValueError('Regeneration is limited to this private run')
    if not folder.exists():return
    n=1
    while folder.with_name(folder.name+'.preserved-'+str(n)).exists():n+=1
    saved=folder.with_name(folder.name+'.preserved-'+str(n))
    folder.rename(saved)
    record(conn,config,dict(kind='stage_preserved',original=str(folder),preserved=str(saved)))


def repair(run_dir):
    """Restore saved generated bytes, retaining corrupt bytes separately."""
    config=load(run_dir)
    with locked(config),h.database(config['database']) as conn:
        projections={}
        for event in events(conn,config):projections.update(event.get('projection_hashes',{}))
        repaired=[];root=Path(config['run_dir']).resolve()
        for name,digest in projections.items():
            path=Path(name)
            if not path.resolve().is_relative_to(root):raise ValueError('Repair cannot write outside the run directory')
            if path.is_file() and h.sha(path.read_bytes())==digest:continue
            raw=gate.blob(conn,digest)
            if h.sha(raw)!=digest:raise ValueError('Saved projection bytes failed integrity validation')
            backup=None
            if path.exists():
                old=path.read_bytes()
                backup=root/'workflow'/'damaged'/h.sha(name)/h.sha(old)
                backup.parent.mkdir(parents=True,exist_ok=True)
                if not backup.exists():backup.write_bytes(old)
            path.parent.mkdir(parents=True,exist_ok=True)
            fd,temp=tempfile.mkstemp(prefix='.repair-',dir=path.parent)
            try:
                with os.fdopen(fd,'wb') as handle:
                    handle.write(raw);handle.flush();os.fsync(handle.fileno())
                os.replace(temp,path)
            finally:
                if os.path.exists(temp):os.unlink(temp)
            repaired.append(dict(path=name,sha256=digest,damaged_copy=str(backup) if backup else None))
        event=dict(kind='projections_repaired',files=repaired)
        if repaired:record(conn,config,event)
        return dict(repaired=repaired,publication_performed=False,
                    next_command=command(config,'workflow','next-task','--run-dir',config['run_dir']))


def initialize(run_dir, database, registry, run_id, *, start=None, end=None,
               directories=(), archive=None, mode='preview', trial=None):
    run_dir = Path(run_dir).resolve()
    if mode not in ('preview', 'publish'):
        raise ValueError('Workflow mode must be preview or publish')
    config = dict(schema_version=VERSION, run_dir=str(run_dir), database=str(Path(database).expanduser().resolve()),
                  registry=gate.load_registry(registry), run_id=run_id, start=start, end=end,
                  mode=mode, checkout=str(ROOT), archive=str(Path(archive).resolve()) if archive else None,
                  directories=sorted(str(Path(p).resolve()) for p in directories))
    if trial is not None:
        config['trial'] = trial
        if mode != 'preview':raise ValueError('Offline trials are preview-only')
    if not isinstance(run_id, str) or not run_id.strip() or not end:
        raise ValueError('An explicit run ID and resolved reporting cutoff are required')
    contract_path = run_dir/'workflow'/'contract.json'
    if contract_path.exists():
        pinned = read(contract_path)
        if {k:v for k,v in pinned.items() if k != 'baseline_capture'} != config:
            raise ValueError('Workflow inputs are pinned; use the original arguments or a new run directory')
        write(run_dir/'workflow'/'registry.json', pinned['registry'], immutable=True)
        return dict(run_dir=str(run_dir), contract_sha256=h.sha(pinned), mode=mode,
                    next_command=command(pinned, 'workflow', 'next-task', '--run-dir', str(run_dir)))
    with h.database(config['database']) as conn:
        gate.target(conn, config['registry']['stream'])
        # Recover a committed initialization whose file projection was interrupted.
        previous = [json.loads(r['payload']).get('workflow', {}) for r in conn.execute(
            "SELECT payload FROM captures WHERE stream LIKE 'workflow:%' ORDER BY seq")]
        recovered = next((e['config'] for e in previous if e.get('kind') == 'initialized'
                          and e['config'].get('run_dir') == str(run_dir)), None)
        if recovered is not None:
            if {k:v for k,v in recovered.items() if k != 'baseline_capture'} != config:
                raise ValueError('Database already pins different workflow inputs for this directory')
            write(contract_path, recovered, immutable=True)
            write(run_dir/'workflow'/'registry.json', recovered['registry'], immutable=True)
            return dict(run_dir=str(run_dir), contract_sha256=h.sha(recovered), mode=mode,
                        next_command=command(recovered, 'workflow', 'next-task', '--run-dir', str(run_dir)))
        # Validate reporting boundaries now, before creating any workflow state.
        opinions.window(conn, config['registry']['stream'], start, end, 30)
        baseline = h.latest_finalized(conn, config['registry']['stream'])
        config['baseline_capture'] = baseline['capture_id'] if baseline else None
        record(conn, config, dict(kind='initialized', config=config))
    write(contract_path, config, immutable=True)
    write(run_dir/'workflow'/'registry.json', config['registry'], immutable=True)
    return dict(run_dir=str(run_dir), contract_sha256=h.sha(config), mode=mode,
                next_command=command(config, 'workflow', 'next-task', '--run-dir', str(run_dir)))


def load(run_dir):
    path = Path(run_dir).resolve()/'workflow'/'contract.json'
    config = read(path)
    if config.get('schema_version') != VERSION or config.get('run_dir') != str(Path(run_dir).resolve()):
        raise ValueError('Invalid or relocated workflow contract')
    if config.get('checkout') != str(ROOT):
        raise ValueError('Use the pinned workflow checkout: ' + config.get('checkout', 'unknown'))
    with h.database(config['database']) as conn:
        saved = events(conn, config)
        if not saved or saved[0] != dict(kind='initialized', config=config):
            raise ValueError('Workflow contract does not match its database record')
        if any(e.get('kind') == 'relocation_committed' for e in saved):
            target = next(e['config']['run_dir'] for e in saved if e.get('kind') == 'relocation_committed')
            raise ValueError('Workflow relocated; use its new binding at ' + target)
        if config.get('relocated_from'):
            from flwu.workflow_relocation import validate_lineage
            validate_lineage(conn, config)
    return config


def command(config, *args):
    """Commands bind interpreter and checkout, independent of editable installs."""
    import sys
    if tuple(map(str,args))==('workflow','next-task','--run-dir',config['run_dir']):
        # Standard initialization/acquisition/continuation advertises the checked
        # inline entry point. The raw next-task API remains explicit compatibility.
        from flwu.workflow_short import checked_command
        return checked_command(config,'next')
    return shlex.join(['env', 'PYTHONDONTWRITEBYTECODE=1', 'PYTHONPATH='+str(ROOT/'src'),
                       sys.executable, '-m', 'flwu', *map(str, args)])


def acquisition_command(config):
    return command(config, 'workflow', 'acquire', '--run-dir', config['run_dir'])


def acquire(run_dir):
    config = load(run_dir)
    from flwu.acquisition import acquisition
    with locked(config), acquisition(config['database'],config['run_id'],'workflow acquire'), h.database(config['database']) as conn:
        pinned=any(e['run_id']==config['run_id'] and e['checkpoint']=='update-contract'
                   for e in opinions.events(conn,config['registry']['stream']))
        baseline=h.latest_finalized(conn,config['registry']['stream'])
        if not pinned and not config['start'] and (baseline['capture_id'] if baseline else None)!=config['baseline_capture']:
            raise ValueError('Finalized baseline changed before acquisition; initialize a new workflow')
        kwargs = {}
        if config.get('trial'):
            from flwu.workflow_trial import Transport
            kwargs['fetch'] = Transport(config)
        queue = update.run(conn, config['registry'], config['run_id'], config['run_dir'],
                           start=config['start'], end=config['end'], **kwargs)
        return dict(phase='acquired', acquisition_complete=queue['acquisition_complete'],
                    publication_performed=False, queue=str(Path(config['run_dir'])/'update-queue.json'),
                    next_command=command(config,'workflow','next-task','--run-dir',config['run_dir']))


@contextmanager
def locked(config):
    path = Path(config['run_dir'])/'workflow'/'coordinator.lock'
    with path.open('a+') as handle:
        try:
            fcntl.flock(handle, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError:
            raise ValueError('Workflow coordinator is active; wait for that command, do not restart it') from None
        try:
            yield
        finally:
            fcntl.flock(handle, fcntl.LOCK_UN)


def source_decision_history(conn, config, *, run_dir=None):
    """Latest source decisions across this run's preserved path bindings.

    Source packets remain immutable, including their original recorded paths.
    The physical root can differ while relocation is pending.
    """
    root = Path(run_dir or config['run_dir'])
    bindings = []
    current = config
    while True:
        bindings.append(current)
        lineage = current.get('relocated_from')
        if not lineage:
            break
        from flwu.workflow_relocation import validate_lineage
        validate_lineage(conn, current, run_dir=root)
        current = read(root/'workflow'/'relocations'/lineage['contract_sha256']/'contract.json')
    decisions = {}
    for binding in reversed(bindings):
        for decision in events(conn, binding):
            if decision['kind'] == 'decision' and decision['task']['kind'] == 'source_review':
                receipt = decision['receipt']
                decisions[(receipt['source_id'], receipt['observation_capture_id'])] = decision
    return decisions, len(bindings)


def verify_source_decisions(conn, config, *, run_dir=None):
    """A path move must not silently clear an interrupted domain correction."""
    decisions, bindings = source_decision_history(conn, config, run_dir=run_dir)
    domain_reviews = {}
    for review in gate.reviews(conn, config['registry']['stream']):
        domain_reviews[(review['source_id'], review['observation_capture_id'])] = review
    for key, decision in decisions.items():
        domain = domain_reviews.get(key)
        if not domain or domain['receipt_sha256'] != h.sha(decision['receipt']):
            raise ValueError('Source review and coordinator decision disagree for ' +
                             decision['packet_sha256'] + '; resume the exact workflow revise '
                             'correction before preparing or publishing downstream artifacts')
    return dict(bindings_checked=bindings, source_decisions_checked=len(decisions))


def review_decision(conn, config, supplied):
    """Resolve a source decision from the same run before or after its move."""
    result = accepted(conn, config).get(supplied.get('packet_sha256'))
    if result is None and supplied.get('kind') == 'source_review':
        history, _ = source_decision_history(conn, config)
        result = next((e for e in history.values()
                       if e['packet_sha256'] == supplied.get('packet_sha256')), None)
    return result


def latest_queue(conn, config, *, refresh=False):
    registry = config['registry']
    saved = [e for e in opinions.events(conn, registry['stream']) if e['run_id']==config['run_id']]
    event = next((e for e in reversed(saved) if e['checkpoint']=='update-result'), None)
    if event is None:
        return None
    if refresh:
        # A domain correction commits before its coordinator decision. Never let
        # another stage publish from that half-completed pair after interruption.
        verify_source_decisions(conn, config)
        return update.refresh(conn, registry, config['run_id'], config['run_dir'])
    raw = gate.blob(conn, event['queue_sha256'])
    if h.sha(raw) != event['queue_sha256']:
        raise ValueError('Saved standard queue checksum mismatch')
    queue = json.loads(raw)
    if queue['run_id'] != config['run_id'] or queue['bounds'] != event['bounds']:
        raise ValueError('Saved standard queue identity mismatch')
    return queue


def accepted(conn, config):
    return {e['packet_sha256']:e for e in events(conn, config) if e['kind']=='decision'}


def source_correction(conn, config, queue, *, emit=False):
    """Recover deficient current-run reviews without mutating accepted history.

    Independent machine reuse from valid older evidence is sufficient. Otherwise
    return the existing explicit correction command, not a new accepted packet.
    """
    from flwu.raw_comparison import review_quality_issue
    from flwu.review_withdrawal import withdrawals
    withdrawn = withdrawals(conn,config['registry']['stream'])
    pending={(t['source_id'],t['observation']['capture_id']) for t in queue['source_reviews']['tasks']
             if t.get('observation') and t['reason'] not in ('retrieval_failed','not_fetched')}
    history,_=source_decision_history(conn,config)
    for key,old in history.items():
        issue=(withdrawn.get(h.sha(old['receipt']),{}).get('reason')
               or review_quality_issue(old['receipt'].get('raw_change_review')))
        if key not in pending or not issue:continue
        task=old['task'];folder=projection_folder(config,'tasks')/task['packet_sha256']
        if not emit:
            return dict(phase='source_review_correction',complete=False,identity=task['identity'],
                        acquisition_complete=queue['acquisition_complete'],explanation=issue,
                        next_command=command(config,'workflow','next-task','--run-dir',config['run_dir']))
        packet_path=folder/'accepted-packet.json';receipt_path=folder/'correction-receipt.json'
        result=dict(phase='source_review_correction',complete=False,identity=task['identity'],
                    acquisition_complete=queue['acquisition_complete'],explanation=issue,
                    predecessor=h.sha(old),correction_reason='Replace unsupported review with evidence-bound correction',
                    packet=str(packet_path),save_receipt=str(receipt_path),
                    command=command(config,'workflow','revise','--run-dir',config['run_dir'],
                        '--packet',str(packet_path),'--receipt',str(receipt_path),
                        '--predecessor',h.sha(old),'--reason','Replace unsupported review with evidence-bound correction'))
        if emit:
            # The accepted packet may bind a retired checkout. Preserve its exact
            # body locally for revise, but use current queued paths for reading.
            write(packet_path,task,immutable=True)
            current=next(t for t in tasks(conn,config,queue)
                         if t['kind']=='source_review' and t['identity']==task['identity'])
            result.update(materialize(config,current,conn))
            result['packet']=str(packet_path)
            template=read(result['receipt_template'])
            result['receipt_template']=str(folder/('correction-template-v7-'+h.sha(template)+'.json'))
            write(Path(result['receipt_template']),template,immutable=True)
            write(folder/'correction-guide.json',dict(issue=issue,prior_receipt=old['receipt'],
                instructions='Read original comparison/decoded fields. Explain each observed difference; do not duplicate boilerplate, append indices to generic prose, or infer no change from identical text. '
                             'Use workflow revise with the returned predecessor and reason; preserve the accepted packet/receipt and do not reacquire. '
                             'If significance cannot be established, leave this correction unfinished and report the specific missing evidence.'))
            result['correction_guide']=str(folder/'correction-guide.json')
            # materialize returns the normal submission command; restore correction.
            result['save_receipt']=str(receipt_path)
            result['command']=command(config,'workflow','revise','--run-dir',config['run_dir'],
                '--packet',str(packet_path),'--receipt',str(receipt_path),
                '--predecessor',h.sha(old),'--reason',result['correction_reason'])+' --advance'
        return result
    return None


def projection_folder(config, category):
    """Keep path-bound task/acceptance files separate after a checkout move."""
    folder = Path(config['run_dir'])/'workflow'/category
    if config.get('relocated_from'):
        folder = folder/'bindings'/h.sha(config)
    return folder


def packet(config, kind, identity, inputs, template, instructions, *, checks=()):
    from flwu.workflow_contracts import contract
    body = dict(schema_version=VERSION, kind=kind, identity=identity, inputs=inputs,
                receipt_template=template, instructions=instructions, completion_checks=list(checks),
                output_contract=contract(kind,template))
    digest = h.sha(body)
    folder = projection_folder(config, 'tasks')/digest
    body.update(packet_sha256=digest, packet_path=str(folder/'packet.json'),
                receipt_path=str(folder/'receipt.json'))
    body['submit_command'] = command(config, 'workflow', 'submit', '--run-dir', config['run_dir'],
                                     '--packet', body['packet_path'], '--receipt', body['receipt_path'])
    return body


def materialize(config, task, conn=None):
    """Legacy maintenance/downstream view; routine reviews use compact cards."""
    if conn is not None:
        # Only the packet about to be read needs its projections repaired.
        # Acceptance still checks quotations against SQLite originals.
        if task['kind'] == 'source_review':
            gate.export_task(conn, task['inputs'], Path(config['run_dir'])/'source-reviews',
                             config['registry']['review_protocol'])
